let language = 'pl';
const localizedBindings = new Map();
const resolveText = value => typeof value === 'function' ? value() : value;
function t(polish, values = {}) {
  if (!Object.hasOwn(translations, polish)) throw new Error(`Missing translation: ${polish}`);
  return () => (language === 'pl' ? polish : translations[polish])
    .replace(/\{(\w+)\}/g, (_, key) => resolveText(values[key]));
}
function bindText(node, value, attribute = null) {
  let bindings = localizedBindings.get(node);
  if (!bindings) localizedBindings.set(node, bindings = new Map());
  const render = () => {
    if (attribute) node.setAttribute(attribute, resolveText(value));
    else node.textContent = resolveText(value);
  };
  bindings.set(attribute, render);
  render();
}
function initializeLanguage() {
  const walker = document.createTreeWalker(document, NodeFilter.SHOW_TEXT, {
    acceptNode: node => node.parentElement?.closest('script,style')
      ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT,
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const text = node.textContent.replace(/\s+/g, ' ').trim();
    if (Object.hasOwn(translations, text)) {
      const leading = node.textContent.match(/^\s*/)[0];
      const trailing = node.textContent.match(/\s*$/)[0];
      const translated = t(text);
      bindText(node, () => leading + translated() + trailing);
    }
  }
  document.querySelectorAll('[aria-label]').forEach(node => {
    const text = node.getAttribute('aria-label');
    if (Object.hasOwn(translations, text)) bindText(node, t(text), 'aria-label');
  });
  document.getElementById('language').addEventListener('change', event => {
    language = event.target.value;
    document.documentElement.lang = language;
    localizedBindings.forEach(bindings => bindings.forEach(render => render()));
  });
}
initializeLanguage();
